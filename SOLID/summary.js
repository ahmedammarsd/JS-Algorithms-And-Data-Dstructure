// ✅ Final Summary: SOLID Principles

// 1. S — Single Responsibility Principle (SRP)
// A class/module/component should have one reason to change.
// Why: Keeps code clean, testable, reusable.
// How: Split responsibilities (UI, logic, persistence).

// 2. O — Open/Closed Principle (OCP)
// Software entities should be open for extension, closed for modification.
// Why: Add new features without breaking old code.
// How: Use composition, strategies, or props instead of “if/else” for every case.

// 3. L — Liskov Substitution Principle (LSP)
// Subclasses should be substitutable for their base class.
// Why: Keeps polymorphism safe.
// How: Ensure subtypes respect contracts.

// 4. I — Interface Segregation Principle (ISP)
// Clients shouldn’t be forced to depend on methods they don’t use.
// Why: Avoid “fat” interfaces/components.
// How: Break large interfaces/props into smaller, role-specific ones.

// 5. D — Dependency Inversion Principle (DIP)
// High-level modules shouldn’t depend on low-level modules. Both depend on abstractions.
// Why: Increases testability, flexibility.
// How: Use dependency injection, abstract services, or providers.

// Final Review (Memory-Friendly)
// Think of SOLID like building a house:
// S (Single Responsibility): Each worker has one job (plumber ≠ electrician).
// O (Open/Closed): Add a new room without tearing down the whole house.
// L (Liskov Substitution): A new door should fit in place of the old one.
// I (Interface Segregation): Don’t give a worker all tools if they only need a hammer.
// D (Dependency Inversion): Architects design based on blueprints (abstractions), not on which hammer brand is used.
